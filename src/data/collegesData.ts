function stemWord(word: string): string {
  if (word.endsWith('ies') && word.length > 5) {
    return word.slice(0, -3) + 'y'; // universities -> university
  }
  if (word.endsWith('es') && word.length > 4) {
    return word.slice(0, -2); // branches -> branch
  }
  if (word.endsWith('s') && !word.endsWith('ss') && word.length > 3) {
    return word.slice(0, -1); // colleges -> college, institutes -> institute
  }
  return word;
}

/**
 * Normalizes query string and scores each institution across:
 * - Exact name / acronym / alias match
 * - Partial prefix match
 * - Tokenized multi-word search (supporting city + college combination like "Global Academy Bengaluru", "RV Bangalore", "BMS Bangalore", "engineering colleges mysore")
 * - Typo and punctuation insensitivity
 */
export function computeMatchScore(
  item: CollegeItem,
  raw: string,
  rawLower: string,
  clean: string,
  tokens: string[]
): number {
  const nameNorm = normalizeString(item.name);
  const nameWords = nameNorm.split(' ').filter(Boolean);
  const cityNorm = normalizeString(item.city);
  const cityAlias = CITY_ALIASES[cityNorm] || cityNorm;
  const stateNorm = normalizeString(item.state);
  const univNorm = item.university ? normalizeString(item.university) : '';
  const affNorm = item.affiliation ? normalizeString(item.affiliation) : '';
  const typeNorm = item.institutionType ? normalizeString(item.institutionType) : '';
  const shortLower = item.shortName ? item.shortName.toLowerCase() : '';
  const aliasesLower = (item.aliases || []).map((a) => a.toLowerCase());
  const aliasesNorm = (item.aliases || []).map((a) => normalizeString(a));

  // 1. Exact Name Match
  if (nameNorm === clean || item.name.toLowerCase() === rawLower) {
    return 2000;
  }

  // 2. Exact Acronym / Alias Match (e.g. "GAT", "RVCE", "BMSCE", "NITK", "PES", "RV")
  if (
    shortLower === rawLower ||
    shortLower === clean ||
    aliasesLower.includes(rawLower) ||
    aliasesNorm.includes(clean)
  ) {
    return 1800;
  }

  // 3. Name starts with clean query (e.g. "Global Academy" -> "Global Academy of Technology")
  if (nameNorm.startsWith(clean)) {
    return 1600;
  }

  // 4. Any alias starts with clean query
  if (aliasesNorm.some((a) => a.startsWith(clean))) {
    return 1400;
  }

  // 5. Short code prefix match
  if (clean.length >= 2 && clean.length <= 6) {
    if (shortLower.startsWith(clean)) {
      return 1300;
    }
    if (aliasesLower.some((a) => a.startsWith(clean))) {
      return 1250;
    }
  }

  // 6. Name contains entire clean query as phrase
  if (nameNorm.includes(clean)) {
    return 1200;
  }

  // 7. Any alias contains entire clean query
  if (aliasesNorm.some((a) => a.includes(clean))) {
    return 1100;
  }

  // 8. Multi-token evaluation (Handles "RV Bangalore", "BMS Bangalore", "Global Academy Bengaluru", "engineering colleges mysore")
  let allTokensMatch = true;
  let tokenScore = 0;

  for (const token of tokens) {
    const tokenCityAlias = CITY_ALIASES[token] || token;
    const tokenStem = stemWord(token);
    let tokenMatched = false;

    // A. Check exact alias or shortName match (crucial for "RV Bangalore" -> "RV")
    if (aliasesLower.includes(token) || shortLower === token) {
      tokenMatched = true;
      tokenScore += 300;
    }
    // B. Check word in name (exact or stemmed)
    else if (
      nameWords.includes(token) ||
      nameWords.includes(tokenStem) ||
      nameWords.some((w) => stemWord(w) === tokenStem)
    ) {
      tokenMatched = true;
      tokenScore += 200;
    }
    // C. Check prefix of word in name (for length >= 3)
    else if (token.length >= 3 && nameWords.some((w) => w.startsWith(token))) {
      tokenMatched = true;
      tokenScore += 150;
    }
    // D. City match (direct or alias, e.g. "bangalore" -> "bengaluru")
    else if (
      cityNorm === token ||
      cityAlias === tokenCityAlias ||
      cityNorm.includes(token)
    ) {
      tokenMatched = true;
      tokenScore += 180;
    }
    // E. State match
    else if (stateNorm === token || stateNorm.includes(token)) {
      tokenMatched = true;
      tokenScore += 80;
    }
    // F. Type or University or Affiliation match (e.g. "engineering", "ayurveda")
    else if (
      typeNorm.includes(token) ||
      typeNorm.includes(tokenStem) ||
      univNorm.includes(token) ||
      univNorm.includes(tokenStem) ||
      affNorm.includes(token) ||
      affNorm.includes(tokenStem)
    ) {
      tokenMatched = true;
      tokenScore += 100;
    }
    // G. Substring match in name (only for tokens length >= 4 to avoid 2-letter noise)
    else if (token.length >= 4 && (nameNorm.includes(token) || nameNorm.includes(tokenStem))) {
      tokenMatched = true;
      tokenScore += 120;
    }
    // H. Substring in aliases
    else if (token.length >= 4 && aliasesNorm.some((a) => a.includes(token) || a.includes(tokenStem))) {
      tokenMatched = true;
      tokenScore += 90;
    }

    if (!tokenMatched) {
      allTokensMatch = false;
      break;
    }
  }

  if (allTokensMatch && tokens.length > 0) {
    return 600 + tokenScore;
  }

  return 0;
}

/**
 * Filter and score colleges matching query string against name, aliases, city, state, and affiliation.
 * Returns up to `limit` institutions ranked by relevance.
 */
export function searchColleges(query: string, limit = 8): CollegeItem[] {
  const raw = (query || '').trim();
  if (!raw) {
    return COLLEGES_DATA.slice(0, limit);
  }

  const clean = normalizeString(raw);
  const rawLower = raw.toLowerCase();
  const tokens = clean.split(' ').filter(Boolean);

  const scored: { item: CollegeItem; score: number }[] = [];

  for (const item of COLLEGES_DATA) {
    const score = computeMatchScore(item, raw, rawLower, clean, tokens);
    if (score > 0) {
      scored.push({ item, score });
    }
  }

  scored.sort((a, b) => b.score - a.score);

  return scored.slice(0, limit).map((s) => s.item);
}
